"""Install the reviewed V7/V8 lower-body poses as the player North V6 walk.

The staged art improves canonical leg poses but does not solve the measured
world-space support-foot slide. Keep that motion limitation explicit in the
runtime manifest and follow-up audit.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageChops


ROOT = Path(__file__).resolve().parents[1]
STAGED = ROOT / "output/animation-overhaul/player-walk-cross-view-v5/leg-phase-correction-v8"
CANDIDATE = STAGED / "north-v8-leg-phase-candidate-strip.png"
CANDIDATE_REPORT = STAGED / "north-v8-candidate-report.json"
V5 = ROOT / "assets/generated/player-walk-v5/walk_north.png"
RUNTIME_REL = Path("assets/generated/player-walk-v6/walk_north.png")
RUNTIME = ROOT / RUNTIME_REL
SPEC = ROOT / "character-motion/rabbit-worker.json"
PLAYER_ART = ROOT / "src/player_walk_art.lua"
MANIFEST = RUNTIME.parent / "manifest.json"
FRAME = 512
EXPECTED_V5 = "09cd04db24b729e0d963590f2d24e1175f0e0cace11057c8929ff37be99af9bf"
EXPECTED_CANDIDATE = "7c2a796d8551785c33b6cdc9c8e6c5816dda695975823551d99cabcaf3ab0922"
EXPECTED_PLAYER_ART_V5 = "d1ed42fdfabd60fbb80860bf80bb20912745e6f4b3e197a57aa0158cc4194ebd"
EXPECTED_SPEC_V5 = "81ce313e2c790223cfd5980563986fc6a2b16e7c1603ff0ad8cd360cd79955b1"
PHASES = (2, 4, 6, 8)


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def visible_box(frame: Image.Image) -> tuple[int, int, int, int]:
    box = frame.getchannel("A").point(lambda value: 255 if value > 16 else 0).getbbox()
    if box is None:
        raise SystemExit("Candidate contains an empty phase")
    return box


def split_strip(path: Path) -> list[Image.Image]:
    image = Image.open(path).convert("RGBA")
    if image.size != (FRAME * 8, FRAME):
        raise SystemExit(f"Expected 4096x512 candidate strip, got {image.size}")
    return [image.crop((index * FRAME, 0, (index + 1) * FRAME, FRAME)) for index in range(8)]


def lua(value) -> str:
    if isinstance(value, dict):
        return "{" + ",".join("[" + json.dumps(key) + "]=" + lua(item) for key, item in value.items()) + "}"
    if isinstance(value, list):
        return "{" + ",".join(lua(item) for item in value) + "}"
    return json.dumps(value)


def build(apply: bool) -> None:
    candidate_bytes = CANDIDATE.read_bytes()
    if sha(V5.read_bytes()) != EXPECTED_V5:
        raise SystemExit("Installed V5 base changed; review before promoting V6")
    if sha(candidate_bytes) != EXPECTED_CANDIDATE:
        raise SystemExit("Staged V8 strip changed; rebuild and re-review before promoting")

    report = json.loads(CANDIDATE_REPORT.read_text(encoding="utf-8"))
    if report.get("base_v5_sha256") != EXPECTED_V5 or report.get("candidate_runtime_changes") is not False:
        raise SystemExit("Candidate provenance does not match the reviewed V8 report")
    if report.get("corrected_phases") != list(PHASES):
        raise SystemExit("Expected the reviewed V7/V8 pose phases 2, 4, 6 and 8")

    original_frames = split_strip(V5)
    candidate_frames = split_strip(CANDIDATE)
    boxes = []
    for index, (original, candidate) in enumerate(zip(original_frames, candidate_frames), start=1):
        box = visible_box(candidate)
        height = box[3] - box[1]
        if not 408 <= height <= 413 or not 465 <= box[3] <= 469:
            raise SystemExit(f"Phase {index} misses the accepted height/baseline band: {box}")
        if index in PHASES:
            if Image.eval(ImageChops.difference(original, candidate).getchannel("A"), lambda p: p).getbbox() is None:
                raise SystemExit(f"Expected phase {index} to contain an art correction")
            if ImageChops.difference(original.crop((0, 0, FRAME, 360)), candidate.crop((0, 0, FRAME, 360))).getbbox():
                raise SystemExit(f"Phase {index} changed preserved upper-body pixels")
        elif ImageChops.difference(original, candidate).getbbox():
            raise SystemExit(f"Unexpected unreviewed change in phase {index}")
        if any(candidate.getpixel(point)[3] != 0 for point in ((0, 0), (FRAME - 1, 0), (0, FRAME - 1), (FRAME - 1, FRAME - 1))):
            raise SystemExit(f"Phase {index} has opaque corner residue")
        boxes.append(list(box))

    runtime_hash = sha(candidate_bytes)
    module = {
        "paths": {"rabbit-worker": {"walk_north": RUNTIME_REL.as_posix()}},
        "anchors": {"rabbit-worker": {"walk_north": [{"x": 256, "y": 465} for _ in range(8)]}},
        "metrics": {"rabbit-worker": {"walk_north": boxes}},
    }
    module_text = "-- Generated by tools/install_player_north_v8.py.\nreturn " + lua(module) + "\n"
    current_module_hash = sha(PLAYER_ART.read_bytes()) if PLAYER_ART.exists() else None
    current_spec_hash = sha(SPEC.read_bytes())
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    active_path = spec["animations"]["walk_north"]["path"]
    if active_path not in ("assets/generated/player-walk-v5/walk_north.png", RUNTIME_REL.as_posix()):
        raise SystemExit(f"Unexpected active North walk path: {active_path}")
    if active_path.endswith("player-walk-v5/walk_north.png") and current_spec_hash != EXPECTED_SPEC_V5:
        raise SystemExit("Rabbit motion spec changed since V5; review before updating it")
    if current_module_hash not in (EXPECTED_PLAYER_ART_V5, sha(module_text.encode("utf-8"))):
        raise SystemExit("Player walk art module changed since V5; review before updating it")
    spec["animations"]["walk_north"]["path"] = RUNTIME_REL.as_posix()
    updated_spec = json.dumps(spec, indent=2) + "\n"

    manifest = {
        "version": 1,
        "status": "installed; root-reviewed pose art; planted-foot travel remains open" if apply else "staged installation plan; runtime unchanged",
        "scope": "V5 north walk with V7 weight-down phases 2/6 and V8 knee-up phases 4/8; no extra in-betweens",
        "runtime_path": RUNTIME_REL.as_posix(),
        "runtime_sha256": runtime_hash,
        "frame_size": [FRAME, FRAME],
        "frame_count": 8,
        "nominal_fps_at_base_speed": 7.75,
        "base_strip": "assets/generated/player-walk-v5/walk_north.png",
        "base_strip_sha256": EXPECTED_V5,
        "source_candidate": CANDIDATE.relative_to(ROOT).as_posix(),
        "source_candidate_sha256": runtime_hash,
        "accepted_generation_scale": report["fixed_scale"],
        "phase_order": ["left_contact", "left_weight_down", "right_passing", "right_knee_up", "right_contact", "right_weight_down", "left_passing", "left_knee_up"],
        "changed_phases": list(PHASES),
        "phase_metrics_alpha_gt16_bbox": boxes,
        "provenance_report": CANDIDATE_REPORT.relative_to(ROOT).as_posix(),
        "support_foot_motion": {
            "status": "still under review; unchanged from V5",
            "contact_to_passing_slip_pixels": [-39.814, -40.186],
            "pixels_per_pose": 20,
            "note": "Key-pose edits improve loading and lifted-boot readability but do not establish world-space foot lock.",
        },
        "root_review": "Five-view review found coherent visible body scale and outline weight. V7/V8 lower-body art is installed as a pose-quality improvement; production capture success does not establish planted-foot lock. Resolve a feasible articulation/timing contract in a separate motion follow-up.",
    }

    if not apply:
        plan = STAGED / "north-v6-install-plan.json"
        plan.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        print(json.dumps({"status": manifest["status"], "target": RUNTIME_REL.as_posix(), "sha256": runtime_hash, "frames": boxes}, indent=2))
        return

    RUNTIME.parent.mkdir(parents=True, exist_ok=True)
    if RUNTIME.exists() and sha(RUNTIME.read_bytes()) != runtime_hash:
        raise SystemExit(f"Refusing to overwrite a different runtime asset: {RUNTIME}")
    RUNTIME.write_bytes(candidate_bytes)
    PLAYER_ART.write_text(module_text, encoding="utf-8")
    SPEC.write_text(updated_spec, encoding="utf-8")
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    (STAGED / "north-v6-install-plan.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"status": manifest["status"], "runtime": str(RUNTIME.relative_to(ROOT)), "sha256": runtime_hash, "frames": boxes}, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true", help="install V6 and update player walk metadata")
    build(parser.parse_args().apply)
