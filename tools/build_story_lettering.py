"""Build the cutscene's transparent, beveled sprite alphabet from a bundled font."""

from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageFont


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/fonts/BarlowCondensed-SemiBold.ttf"
ATLAS = ROOT / "assets/generated/story-intro/story-lettering-v1.png"
DATA = ROOT / "src/story_lettering_data.lua"
CHARS = "".join(chr(code) for code in range(32, 127))
CELL_W, CELL_H, COLS = 90, 92, 16
FONT_SIZE = 58


def make_glyph(char: str, font: ImageFont.FreeTypeFont) -> Image.Image:
    size = (CELL_W, CELL_H)
    mask = Image.new("L", size)
    ImageDraw.Draw(mask).text((12, 65), char, font=font, fill=255, anchor="ls")
    outline = mask.filter(ImageFilter.MaxFilter(9))
    shadow = ImageChops.offset(outline, 4, 6)
    top_edge = ImageChops.subtract(mask, ImageChops.offset(mask, 0, 2))

    result = Image.new("RGBA", size)
    result.paste((12, 22, 25, 0), (0, 0, *size))
    result.paste((12, 24, 27, 155), (0, 0, *size), shadow)
    for offset in range(6, 0, -1):
        depth = ImageChops.offset(mask, offset, offset)
        result.paste((76, 45, 28, 255), (0, 0, *size), depth)
    result.paste((20, 38, 40, 255), (0, 0, *size), outline)
    gradient = Image.new("RGBA", size)
    pixels = gradient.load()
    for y in range(CELL_H):
        t = min(1, max(0, (y - 20) / 57))
        r = round(255 - 26 * t)
        g = round(246 - 52 * t)
        b = round(209 - 111 * t)
        for x in range(CELL_W):
            pixels[x, y] = (r, g, b, 255)
    result.paste(gradient, (0, 0), mask)
    result.paste((255, 255, 237, 255), (0, 0, *size), top_edge)
    return result


def main() -> None:
    font = ImageFont.truetype(str(SOURCE), FONT_SIZE)
    rows = (len(CHARS) + COLS - 1) // COLS
    atlas = Image.new("RGBA", (COLS * CELL_W, rows * CELL_H))
    advances = []
    for index, char in enumerate(CHARS):
        atlas.alpha_composite(make_glyph(char, font),
                             ((index % COLS) * CELL_W, (index // COLS) * CELL_H))
        advances.append(max(17, round(font.getlength(char) + 7)))
    ATLAS.parent.mkdir(parents=True, exist_ok=True)
    atlas.save(ATLAS)
    DATA.write_text(
        "-- Generated by tools/build_story_lettering.py; ASCII 32 through 126.\n"
        f"return {{cellW={CELL_W},cellH={CELL_H},columns={COLS},"
        "advances={" + ",".join(str(value) for value in advances) + "}}\n",
        encoding="utf-8",
    )
    print(f"Wrote {ATLAS.relative_to(ROOT)} and {DATA.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
