"""Package the root-reviewed canonical phase-5 correction; stage by default."""
import argparse
import hashlib
import json
import re
from pathlib import Path
from PIL import Image
import build_luna_player_north_key_v1 as staging

ROOT=Path(__file__).resolve().parents[1]
RUNTIME="assets/generated/player-walk-v3/walk_north.png"


def remove_reviewed_top_residue(image):
    """Remove the isolated source line, retaining every character pixel exactly."""
    original=image
    image=original.copy()
    # Root inspected these four disconnected alpha components above key7's
    # ears. The character starts at y78; this bounded crop ends at y62.
    index=6
    box=(200,54,245,62)
    cell=image.crop((index*512,0,(index+1)*512,512))
    crop=cell.crop(box)
    occupied=sum(pixel[3]>0 for pixel in crop.get_flattened_data())
    assert occupied==102, f"Pinned detached source residue changed: {occupied} pixels"
    assert not cell.crop((0,62,512,78)).getchannel("A").getbbox()
    cleaned=cell.copy()
    cleaned.paste((0,0,0,0),box)
    assert cleaned.crop((0,78,512,512)).tobytes()==cell.crop((0,78,512,512)).tobytes()
    image.paste(cleaned,(index*512,0))
    for i in range(8):
        if i!=index:
            assert image.crop((i*512,0,(i+1)*512,512)).tobytes()==original.crop((i*512,0,(i+1)*512,512)).tobytes()
    return image,occupied


def lua(value):
    if isinstance(value,dict):
        return "{"+",".join("["+json.dumps(key)+"]="+lua(item) for key,item in value.items())+"}"
    if isinstance(value,list):
        return "{"+",".join(map(lua,value))+"}"
    return json.dumps(value)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply",action="store_true")
    args=parser.parse_args()
    staging.main()  # Verifies immutable inputs, exact transform and seven unchanged cells.
    destination=ROOT if args.apply else ROOT/"output/animation-overhaul/player-north-install-preview"
    target=destination/RUNTIME
    target.parent.mkdir(parents=True,exist_ok=True)
    staging_image=Image.open(staging.PROPOSAL_PATH).convert("RGBA")
    cleaned,residue_pixels=remove_reviewed_top_residue(staging_image)
    cleaned.save(target)
    original_anchor_line=next(line for line in (ROOT/"src/character_anchors.lua").read_text().splitlines()
                              if line.strip().startswith("walk_north ="))
    anchors=[{"x":float(x),"y":float(y)} for x,y in re.findall(r"x\s*=\s*([\d.]+),\s*y\s*=\s*([\d.]+)",original_anchor_line)]
    assert len(anchors)==8
    anchors[4]={"x":256,"y":465}
    image=Image.open(target).convert("RGBA")
    metrics=[list(image.crop((i*512,0,(i+1)*512,512)).getchannel("A")
                  .point(lambda alpha:255 if alpha>16 else 0).getbbox()) for i in range(8)]
    art={"paths":{"rabbit-worker":{"walk_north":RUNTIME}},
         "anchors":{"rabbit-worker":{"walk_north":anchors}},
         "metrics":{"rabbit-worker":{"walk_north":metrics}}}
    module=destination/"src/player_walk_art.lua"
    module.parent.mkdir(parents=True,exist_ok=True)
    module.write_text("-- Generated by tools/build_player_north_correction_v1.py.\nreturn "+lua(art)+"\n",encoding="utf-8")
    manifest={"version":2,"scope":"North canonical phase5 correction plus isolated top-line cleanup in phase7; eight-frame cycle preserved; six other cells exact.",
        "source":str(staging.RAW_MASTER.relative_to(ROOT)).replace("\\","/"),"source_sha256":staging.EXPECTED_RAW_SHA256,
        "original_strip":str(staging.ORIGINAL_STRIP.relative_to(ROOT)).replace("\\","/"),
        "original_sha256":staging.EXPECTED_ORIGINAL_STRIP_SHA256,"runtime_path":RUNTIME,
        "runtime_sha256":hashlib.sha256(target.read_bytes()).hexdigest(),
        "review":"Root checked full contact cycle and game-scale comparison; pose5 uses the opposite sole/arm from pose1. The phase7 floating line is disconnected from the ears by 18 transparent rows; character pixels remain exact.",
        "residue_cleanup":{"phase":7,"box":[200,54,245,62],"nonzero_alpha_pixels_removed":residue_pixels,
            "character_pixels_y78_and_below_exact":True},
        "remaining":"Canonical passing/scale concerns and all sixteen-frame transitions remain under review. This is not full gait acceptance."}
    (target.parent/"manifest.json").write_text(json.dumps(manifest,indent=2)+"\n",encoding="utf-8")
    spec=json.loads((ROOT/"character-motion/rabbit-worker.json").read_text(encoding="utf-8"))
    spec["animations"]["walk_north"]["path"]=target.relative_to(ROOT).as_posix()
    (ROOT/"output/animation-overhaul/player-north-install-preview").mkdir(parents=True,exist_ok=True)
    (ROOT/"output/animation-overhaul/player-north-install-preview/staging-spec.json").write_text(json.dumps(spec,indent=2)+"\n",encoding="utf-8")
    print(f"{'Installed' if args.apply else 'Staged'} contained north correction: {target}")


if __name__=="__main__":
    main()
