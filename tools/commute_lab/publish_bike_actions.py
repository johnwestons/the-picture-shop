"""Validate current authored sources and publish only complete registered pages."""
import argparse
import json
import shutil
from PIL import Image
from compile_bike_actions import ROOT,SOURCE,STAGE,REVIEW,sha,mask

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--publish',action='store_true');args=parser.parse_args()
    spec=json.loads((SOURCE/'production.json').read_text());folder=STAGE/'matched'
    registration=json.loads((folder/'registration.json').read_text())
    assert sha((ROOT/spec['approvedUpright']).read_bytes())==spec['approvedUprightSha256'],'Approved upright changed'
    expected={state for j in spec['jobs'] for state in j['states']}
    assert len(expected)==14 and set(registration['completeStates'])==expected
    assert len(registration['frames'])==896
    provenance=[];records={};cells=set()
    for job in spec['jobs']:
        path=ROOT/job['source'];assert path.is_file()
        meta_path=SOURCE/(path.stem.removesuffix('-source')+'.generation.json')
        meta=json.loads(meta_path.read_text())
        assert meta['workspaceSource']==job['source']
        provenance.append({'id':job['id'],'source':job['source'],'sha256':sha(path.read_bytes()),
            'generationRecord':str(meta_path.relative_to(ROOT)).replace('\\','/')})
        for state in job['states']:
            for view in job['views']:records[(state,view+1)]=job
    for row in registration['frames']:
        job=records[(row['state'],row['frame'])]
        assert row['source']==job['source'] and row['sourceSha256']==sha((ROOT/job['source']).read_bytes())
        key=(row['source'],row['sourceCell']);assert key not in cells;cells.add(key)
        b=row['bbox'];assert min(b[0],b[1],320-b[2],320-b[3])>=2
    quality={}
    for state in sorted(expected):
        rows=sorted((r for r in registration['frames'] if r['state']==state),key=lambda r:r['frame'])
        assert [r['frame'] for r in rows]==list(range(1,65))
        image=Image.open(folder/(state+'-64.png')).convert('RGBA');hashes=set()
        for i in range(64):
            tile=image.crop((i%8*320,i//8*320,(i%8+1)*320,(i//8+1)*320))
            assert mask(tile).getbbox();hashes.add(sha(tile.tobytes()))
        assert len(hashes)==64
        jump=max(abs(rows[i]['helmetTop']-rows[(i+1)%64]['helmetTop']) for i in range(64))
        assert jump<=3,(state,'upper-envelope discontinuity',jump)
        for page in range(1,5):
            p=folder/'pages'/f'{state}-{page}.png';assert Image.open(p).size==(1280,1280)
        quality[state]={'views':64,'uniqueCells':64,'maxAdjacentUpperEnvelopeChange':jump,
            'minimumWheelSilhouetteIoU':min(r['wheelSilhouetteIoU'] for r in rows)}
    report={'approvedUprightUnchanged':True,'selectedSheets':56,'authoredActionCells':896,
        'states':quality,'transforms':'Uniform scale and translation only; no mirroring, interpolation or alpha pose blends.',
        'metricSemantics':'Upper envelope may be helmet, shoulder or back depending on the pose; anatomy also requires visual review.',
        'selectedProvenance':provenance}
    REVIEW.mkdir(parents=True,exist_ok=True);(REVIEW/'asset-acceptance.json').write_text(json.dumps(report,indent=2)+'\n')
    (SOURCE/'selected-sources.json').write_text(json.dumps(provenance,indent=2)+'\n')
    if args.publish:
        target=ROOT/'assets/commute/bike/actions-64';target.mkdir(parents=True,exist_ok=True)
        lines=['-- Generated by tools/commute_lab/publish_bike_actions.py; protected upper-rider bounds.','return {']
        for state in sorted(expected):
            for page in range(1,5):shutil.copy2(folder/'pages'/f'{state}-{page}.png',target/f'{state}-{page}.png')
            rows=sorted((r for r in registration['frames'] if r['state']==state),key=lambda r:r['frame'])
            lines.append('    '+state+'={'+','.join(str(r['paintLower']) for r in rows)+'},')
        lines.append('}');(target/'paint_regions.lua').write_text('\n'.join(lines)+'\n')
    print(json.dumps({'states':14,'viewsPerState':64,'authoredCells':896,'published':args.publish,'quality':quality}))

if __name__=='__main__':main()
