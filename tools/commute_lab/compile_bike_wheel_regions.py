"""Fit lower tire arcs mechanically; generate material-region metadata only.

No sprite pixels are changed. The material shader additionally gates its cue
to opaque, dark, low-chroma rubber in these conservative lower wheel annuli.
"""
import json
import math
from pathlib import Path
import numpy as np
from PIL import Image,ImageDraw

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'output/bike-motion-fx-review'
STATES=['upright','boostMid','boost','brakeMid','brake','turnLeftMid','turnLeft',
    'turnRightMid','turnRight','aeroMid','aero','shiftMid','shift','impactMid','impact']

def cells(state):
    if state=='upright':
        image=Image.open(ROOT/'assets/commute/bike/mounted-upright-64-v2.png').convert('RGBA')
        return [image.crop((i%8*320,i//8*320,(i%8+1)*320,(i//8+1)*320)) for i in range(64)]
    result=[]
    for page in range(1,5):
        image=Image.open(ROOT/f'assets/commute/bike/actions-64/{state}-{page}.png').convert('RGBA')
        result.extend(image.crop((i%4*320,i//4*320,(i%4+1)*320,(i//4+1)*320)) for i in range(16))
    return result

def fit(profile,peak):
    bottom=float(np.median(profile[max(0,peak-2):peak+3]))
    left=right=peak
    while left>0 and profile[left-1]>=bottom-12:left-=1
    while right<319 and profile[right+1]>=bottom-12:right+=1
    middle=(left+right)*.5;span=right-left+1
    best=None
    for ry in np.arange(23,33.1,1):
        estimate=span/(2*math.sqrt(1-((ry-12)/ry)**2))
        for rx in [estimate-1,estimate,estimate+1]:
            rx=float(np.clip(rx,8,37))
            for cx in np.arange(middle-2,middle+2.1,1):
                xs=np.arange(max(0,round(cx-rx*.92)),min(320,round(cx+rx*.92)+1))
                actual=profile[xs];valid=actual>=bottom-20
                if valid.sum()<7:continue
                predicted=bottom-ry+ry*np.sqrt(np.maximum(0,1-((xs-cx)/rx)**2))
                score=float(np.median(np.abs(predicted[valid]-actual[valid])))+.025*abs(ry-28)
                if best is None or score<best[0]:best=(score,cx,bottom-ry,rx,ry)
    assert best is not None
    return [round(v,2) for v in best[1:]]

def regions(tile,view):
    alpha=np.asarray(tile)[:,:,3]>=24
    profile=np.where(alpha,np.arange(320)[:,None],-1).max(0)
    smooth=np.convolve(profile,np.ones(5)/5,'same')
    candidates=sorted(range(3,317),key=lambda x:smooth[x],reverse=True)
    peaks=[]
    for x in candidates:
        if smooth[x]<220:break
        if all(abs(x-p)>42 for p in peaks):peaks.append(x)
        if len(peaks)==2:break
    assert peaks
    # End-on wheels overlap; the visible near tire is the only safe region.
    if abs(math.sin(view*math.tau/64))<.5:peaks=peaks[:1]
    wheels=[fit(profile,x) for x in peaks]
    while len(wheels)<2:wheels.append([0,0,0,0])
    return wheels

def main():
    OUT.mkdir(parents=True,exist_ok=True);metadata={};lines=[
        '-- Generated by tools/commute_lab/compile_bike_wheel_regions.py; lower tire arc ellipses.',
        '-- Each row is {cx1,cy1,rx1,ry1,cx2,cy2,rx2,ry2}; no sprite pixels changed.','return {']
    contact=Image.new('RGBA',(1600,1760),(33,49,51));d=ImageDraw.Draw(contact)
    for state in STATES:
        metadata[state]=[];lines.append('    '+state+'={')
        samples=cells(state)
        for i,tile in enumerate(samples):
            wheels=regions(tile,i);metadata[state].append(wheels)
            flat=[v for wheel in wheels for v in wheel]
            lines.append('        {'+','.join(f'{v:g}' for v in flat)+'},')
            if state=='upright':
                preview=tile.copy();mark=ImageDraw.Draw(preview)
                for cx,cy,rx,ry in wheels:
                    if rx:mark.ellipse((cx-rx,cy-ry,cx+rx,cy+ry),outline=(30,245,240,255),width=2)
                contact.alpha_composite(preview.resize((184,184)),(i%8*200+8,i//8*220+28))
                d.text((i%8*200+8,i//8*220+7),f'wheel regions {i+1:02}',fill='white')
        lines.append('    },')
    lines.append('}')
    (ROOT/'assets/commute/bike/wheel_regions.lua').write_text('\n'.join(lines)+'\n')
    (OUT/'wheel-regions.json').write_text(json.dumps(metadata,indent=2)+'\n')
    contact.save(OUT/'wheel-regions-upright-64.png')
    print('Fitted conservative lower-wheel regions for 15 poses, all64 directions; no sprite edits')

if __name__=='__main__':main()
