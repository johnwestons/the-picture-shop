"""Pack independently drawn warehouse views with reviewed ground/door anchors.
No painting, mirroring or silhouette distortion. Immutable generated sources.
"""
from pathlib import Path
from PIL import Image, ImageDraw
import hashlib, json

ROOT=Path(__file__).resolve().parents[2]
source=ROOT/'assets/source/commute-warehouse-v1/side-repair.png'
stage=ROOT/'assets/staging/commute-warehouse-v1'
stage.mkdir(parents=True,exist_ok=True)
im=Image.open(source).convert('RGBA')
assert im.size==(1774,887)
directions=['north','northeast','east','southeast','south','southwest','west','northwest']
# Global source coordinates. Front views register the pedestrian threshold;
# hidden-front views register the center of the projected ground footprint.
anchors=[(220,302),(1553,687),(1115,238),(1696,330),(336,781),(694,791),(1115,659),(638,256)]
targets=[(256,400),(256,380),(256,380),(400,400),(400,400),(300,400),(256,380),(256,380)]
# Rear diagonals in the generated sheet were labeled from observer position;
# remap them to the front-facing direction convention used by the camera.
source_order=[0,7,2,3,4,5,6,1]
atlas=Image.new('RGBA',(2048,1024));views=[]
for i,direction in enumerate(directions):
    col,row=source_order[i]%4,source_order[i]//4
    rect=(round(col*im.width/4),round(row*im.height/2),round((col+1)*im.width/4),round((row+1)*im.height/2))
    tile=im.crop(rect);frame=Image.new('RGBA',(512,512))
    ax,ay=anchors[i];tx,ty=targets[i]
    frame.alpha_composite(tile,(tx-(ax-rect[0]),ty-(ay-rect[1])))
    box=frame.getchannel('A').point(lambda a:255 if a>=16 else 0).getbbox()
    assert box and min(box[0],box[1],512-box[2],512-box[3])>=3,(direction,box)
    atlas.alpha_composite(frame,(i%4*512,i//4*512))
    views.append({'direction':direction,'anchor':list(targets[i]),'registration':'door' if i in (3,4,5) else 'center',
                  'sourceAnchor':list(anchors[i]),'sourceRect':list(rect),'bounds':list(box)})
atlas.save(stage/'warehouse.png')
manifest={'version':1,'status':'staged_for_review','frameSize':512,'columns':4,'rows':2,'scale':1.48,'mirror':False,
          'source':str(source.relative_to(ROOT)),'sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest(),
          'atlasSha256':hashlib.sha256((stage/'warehouse.png').read_bytes()).hexdigest(),
          'prompts':['assets/source/commute-warehouse-v1/prompt.txt','assets/source/commute-warehouse-v1/side-repair-prompt.txt'],
          'generator':'built-in imagegen','views':views}
(stage/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
# Registration metadata is shared with the runtime rather than retyped there.
lines=['-- Generated by tools/commute_lab/compile_warehouse.py; source-space registration.','return {']
for i,v in enumerate(views):
    lines.append("    %s={index=%d,x=%d,y=%d,door=%s,bounds={%s}}," % (v['direction'],i+1,*v['anchor'],
        str(v['registration']=='door').lower(),','.join(map(str,v['bounds']))))
lines.append('}')
(stage/'registration.lua').write_text('\n'.join(lines)+'\n')
print('Eight warehouse views staged; runtime publication requires native scene review.')
