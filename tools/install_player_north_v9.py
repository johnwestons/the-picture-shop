"""Install the reviewed North V9 passing-pose pair as player-walk-v7."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
STAGED = ROOT / "output/animation-overhaul/player-north-v9"
CANDIDATE = STAGED / "north-v9-fullbody-normalized-candidate-strip.png"
CANDIDATE_REPORT = STAGED / "north-v9-candidate-report.json"
BASE = ROOT / "assets/generated/player-walk-v6/walk_north.png"
RUNTIME_REL = Path("assets/generated/player-walk-v7/walk_north.png")
RUNTIME = ROOT / RUNTIME_REL
SPEC = ROOT / "character-motion/rabbit-worker.json"
PLAYER_ART = ROOT / "src/player_walk_art.lua"
MANIFEST = RUNTIME.parent / "manifest.json"
FRAME = 512
EXPECTED_BASE = "7c2a796d8551785c33b6cdc9c8e6c5816dda695975823551d99cabcaf3ab0922"
EXPECTED_CANDIDATE = "8a182527de78fe8d0da5a5b8068ec0019ef08da9513bf29dbb2a74b126bcba33"
CHANGED_PHASES = (3, 7)


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def lua(value) -> str:
    if isinstance(value, dict):
        return "{" + ",".join("[" + json.dumps(key) + "]=" + lua(item) for key, item in value.items()) + "}"
    if isinstance(value, list):
        return "{" + ",".join(lua(item) for item in value) + "}"
    return json.dumps(value)


def boxes(path: Path) -> list[list[int]]:
    sheet = Image.open(path).convert("RGBA")
    if sheet.size != (FRAME * 8, FRAME):
        raise SystemExit(f"Expected an eight-frame 4096x512 strip, got {sheet.size}")
    result = []
    for index in range(8):
        frame = sheet.crop((index * FRAME, 0, (index + 1) * FRAME, FRAME))
        box = frame.getchannel("A").point(lambda value: 255 if value > 16 else 0).getbbox()
        if box is None:
            raise SystemExit(f"Candidate phase {index + 1} is empty")
        if not 408 <= box[3] - box[1] <= 412 or not 465 <= box[3] <= 469:
            raise SystemExit(f"Candidate phase {index + 1} misses accepted geometry: {box}")
        if any(frame.getpixel(point)[3] != 0 for point in ((0, 0), (FRAME - 1, 0), (0, FRAME - 1), (FRAME - 1, FRAME - 1))):
            raise SystemExit(f"Candidate phase {index + 1} has opaque corner residue")
        result.append(list(box))
    return result


def build(apply: bool) -> None:
    candidate_bytes = CANDIDATE.read_bytes()
    if sha(BASE.read_bytes()) != EXPECTED_BASE:
        raise SystemExit("Installed V6 base changed; review before promoting North V7")
    if sha(candidate_bytes) != EXPECTED_CANDIDATE:
        raise SystemExit("Reviewed full-body candidate changed; rebuild and re-review")

    report = json.loads(CANDIDATE_REPORT.read_text(encoding="utf-8"))
    if report.get("fullbody_candidate_sha256") != EXPECTED_CANDIDATE:
        raise SystemExit("Candidate provenance does not match the reviewed North V9 report")
    if report.get("changed_phases") != list(CHANGED_PHASES):
        raise SystemExit("Expected only the phase-3/7 passing-pose pair")
    checks = report.get("fullbody_checks", {})
    if any(int(checks.get(str(index), {}).get("red_or_magenta_fringe_pixels", -1)) != 0
           or int(checks.get(str(index), {}).get("green_fringe_pixels", -1)) != 0
           for index in range(1, 9)):
        raise SystemExit("Candidate contains a flagged color fringe")

    metrics = boxes(CANDIDATE)
    module = {
        "paths": {"rabbit-worker": {"walk_north": RUNTIME_REL.as_posix()}},
        "anchors": {"rabbit-worker": {"walk_north": [{"x": 256, "y": 465} for _ in range(8)]}},
        "metrics": {"rabbit-worker": {"walk_north": metrics}},
    }
    module_text = "-- Generated by tools/install_player_north_v9.py.\nreturn " + lua(module) + "\n"

    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    active_path = spec["animations"]["walk_north"]["path"]
    if active_path not in ("assets/generated/player-walk-v6/walk_north.png", RUNTIME_REL.as_posix()):
        raise SystemExit(f"Unexpected active North walk path: {active_path}")
    spec["animations"]["walk_north"]["path"] = RUNTIME_REL.as_posix()

    manifest = {
        "version": 1,
        "status": "installed; root-reviewed phase-3/7 passing-pose corrections; support-foot travel remains open" if apply else "staged installation plan; runtime unchanged",
        "scope": "V6 North cycle with corrected opposite-owner passing poses at phases 3 and 7; no extra in-betweens",
        "runtime_path": RUNTIME_REL.as_posix(),
        "runtime_sha256": EXPECTED_CANDIDATE,
        "frame_size": [FRAME, FRAME],
        "frame_count": 8,
        "nominal_fps_at_base_speed": 7.75,
        "base_strip": "assets/generated/player-walk-v6/walk_north.png",
        "base_strip_sha256": EXPECTED_BASE,
        "source_candidate": CANDIDATE.relative_to(ROOT).as_posix(),
        "source_candidate_sha256": EXPECTED_CANDIDATE,
        "phase_order": ["left_contact", "left_weight_down", "right_passing", "right_knee_up", "right_contact", "right_weight_down", "left_passing", "left_knee_up"],
        "changed_phases": list(CHANGED_PHASES),
        "phase_metrics_alpha_gt16_bbox": metrics,
        "provenance_report": CANDIDATE_REPORT.relative_to(ROOT).as_posix(),
        "support_foot_motion": {
            "status": "still under review; the new frames separate pass and support boots but do not lock the support sole to the moving world position",
            "contact_to_passing_root_travel": 40,
            "support_sole_local_y_change_px": [0, 0],
            "pixels_per_pose": 20,
            "note": "The remaining contact-to-pass drift is about 40 project pixels at the current cadence. No timing or anchor change is included.",
        },
        "root_review": "The phase-3 right pass and phase-7 left pass now read as distinct, opposite-owner low passing poses at source and runtime sizes. All five authored walk views retain a shared 410px height band (North 408-412px). The selected North median head/torso proxies are 113/112px versus 114/113px in V6; its dark-ink density proxy is 0.05293 versus 0.05210 in V6. Production renderer review passed 32 host/guest captures across desktop and landscape-phone layouts.",
    }

    if not apply:
        plan = STAGED / "north-v7-install-plan.json"
        plan.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        print(json.dumps({"status": manifest["status"], "target": RUNTIME_REL.as_posix(), "sha256": EXPECTED_CANDIDATE, "frames": metrics}, indent=2))
        return

    RUNTIME.parent.mkdir(parents=True, exist_ok=True)
    if RUNTIME.exists() and sha(RUNTIME.read_bytes()) != EXPECTED_CANDIDATE:
        raise SystemExit(f"Refusing to overwrite a different runtime asset: {RUNTIME}")
    RUNTIME.write_bytes(candidate_bytes)
    PLAYER_ART.write_text("-- Generated by tools/install_player_north_v9.py.\nreturn " + lua(module) + "\n", encoding="utf-8")
    SPEC.write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8")
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    (STAGED / "north-v7-install-plan.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"status": manifest["status"], "runtime": str(RUNTIME.relative_to(ROOT)), "sha256": EXPECTED_CANDIDATE, "frames": metrics}, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true", help="install North V7 and update player walk metadata")
    build(parser.parse_args().apply)
