"""Shared activities on real PC/S25 sockets; actor positions are staged fixtures."""
import json,time,subprocess
import os
import run_live_network_journey as N
from live_device import ROOT,adb,DEFAULT_SERIAL,PACKAGE
HOST_ENDPOINT=os.environ.get('TPS_HOST_ENDPOINT','')
N.OUT=ROOT/'output/live-gameplay-20261109/shared-activities';N.OUT.mkdir(exist_ok=True)
N.checks=[]
pc,phone,check,wait=N.pc,N.phone,N.check,N.wait
def interact(label,kind,command,accepted=True):
    return N.action(label,'assert(R.multiplayer:requestInteraction('+json.dumps(kind)+','+json.dumps(command)+'))',accepted)
def scene(scene,x,y,both=False):
    pc("local p=assert(R.multiplayer.players[2]);p.sceneId='%s';p.x=%s;p.y=%s;%s return true"%(scene,x,y,
        "R.World.player.sceneId=p.sceneId;R.World.player.x=p.x+12;R.World.player.y=p.y;R.state.screen='world';" if both else ''))
    phone("R.state.screen='world';R.World.player.sceneId='%s';R.World.player.x=%s;R.World.player.y=%s;return true"%(scene,x,y));time.sleep(.3)
def snap(name):
    (N.OUT/(name+'.png')).write_bytes(adb(DEFAULT_SERIAL,'exec-out','screencap','-p',binary=True))

def tap(x,y):
    adb(DEFAULT_SERIAL,'shell','input','tap',str(round(405.398+x*1080/678)),str(round(y*1080/678)))
    time.sleep(.4)
def game(game,bay,x,y):
    scene(bay,x,y,True)
    if game!='basketball':
        module='air_hockey_screen' if game=='air_hockey' else 'critter_kombat_screen'
        for target in ('pc','phone'):N.call(target,"require('src.screens.%s').enter(R,'%s');return true"%(module,bay))
def main():
    if not HOST_ENDPOINT: raise RuntimeError('Set TPS_HOST_ENDPOINT to the reachable PC address and port, such as <pc-ip>:22122.')
    N.helpers();N.release()
    # A previous interrupted attempt may have saved a traveler inside a store.
    # Clear that starting fixture before staging actors at the arcade cabinets.
    pc("R.state.home.commute=nil;R._commute=nil;require('src.home_residents').get(R.state,R.multiplayer.players[2]).sceneId='warehouse';require('src.air_hockey').matches={};R.multiplayer:markShopDirty(true);return true")
    time.sleep(.5);phone("R._commute=nil;return true")
    game('air_hockey','front_left',506,408)
    check('host_starts_versus_hockey',pc("return require('src.air_hockey').command(R.state,R.World.player,'start_versus')"))
    interact('phone_joins_hockey','roomGame','air_hockey:join')
    before=pc("return require('src.air_hockey').matches.front_left.rightY")
    snap('hockey-before-touch')
    adb(DEFAULT_SERIAL,'shell','input','swipe','598','522','640','565','900')
    after=pc("return require('src.air_hockey').matches.front_left.rightY")
    check('physical_touch_moves_host_paddle',abs(after-before)>5,{'before':before,'after':after})
    snap('hockey-after-touch')
    interact('leave_hockey','roomGame','air_hockey:leave')
    check('hockey_table_reusable',pc("return next(require('src.air_hockey').matches)==nil"))
    game('critter_kombat','front_right',860,436)
    check('host_starts_fight',pc("return require('src.critter_kombat').command(R.state,R.World.player,'start_versus')"))
    tap(270,400)
    tap(480,620)
    check('phone_touch_joins_fight',wait(lambda:phone("return require('src.screens.critter_kombat_screen').page(R)=='select'")))
    pc("assert(require('src.critter_kombat').command(R.state,R.World.player,'ready_mouse'));return true")
    tap(660,340)
    tap(480,576)
    time.sleep(2)
    check('fight_reaches_playing',phone("local m=R.multiplayer:fightSnapshot()[1];return m and m.phase=='playing' and m.right.character=='fox'"))
    snap('kombat-playing')
    before=pc("return require('src.critter_kombat').matches.front_right.right.x")
    adb(DEFAULT_SERIAL,'shell','input','swipe','604','1010','604','1010','700')
    after=pc("return require('src.critter_kombat').matches.front_right.right.x")
    check('physical_touch_moves_host_fighter',abs(after-before)>5,{'before':before,'after':after})
    interact('leave_fight','roomGame','critter_kombat:leave')
    check('host_starts_coop_crisis',pc("return require('src.critter_crisis').command(R.state,R.World.player,'start_coop')"))
    interact('phone_joins_coop_crisis','roomGame','critter_crisis:join')
    check('crisis_both_players',pc("local s=require('src.critter_crisis').sessions.front_right;return s.phase=='playing' and s.players[1]~=nil and s.players[2]~=nil"))
    resident=phone('return R.multiplayer.residentId')
    adb(DEFAULT_SERIAL,'shell','am','force-stop',PACKAGE)
    wait(lambda:pc('return R.multiplayer.players[2]==nil'),seconds=35)
    check('app_kill_removes_guest',True)
    check('disconnect_releases_arcade',pc("return next(require('src.critter_crisis').sessions)==nil"))
    adb(DEFAULT_SERIAL,'shell','am','start','-W','-n',PACKAGE+'/org.love2d.android.GameActivity')
    time.sleep(3)
    phone("assert(R.startLanClient(%s,'Android Worker'));return true"%json.dumps(HOST_ENDPOINT))
    wait(lambda:phone('return R.multiplayer.ready'),seconds=30);N.helpers()
    check('relaunch_retains_resident',phone('return R.multiplayer.residentId')==resident)
    check('relaunch_retains_paid_job',phone('return #R.state.jobs.completed==1 and #R.state.jobs.active==0'))
    # Add the third break-room fixture through the existing test resource editor.
    pc("local E=require('src.save_editor');local okay,reason=E.grantSlot({state=R.state,save=R.Save,useActiveState=true,saveCurrent=function()return R.saveCurrent(true)end},1,'front_left:basketball');assert(okay or reason=='That game is already owned.',reason);return true")
    ball=pc('return R.state.breakroomGames.bays.front_left.ball');scene('front_left',ball['x'],ball['y'])
    interact('pickup_basketball','roomGame','basketball:pickup')
    interact('start_basketball_shot','roomGame','basketball:shot_start')
    interact('release_basketball_shot','roomGame','basketball:shot_release')
    wait(lambda:pc("return R.state.breakroomGames.bays.front_left.ball.mode=='placed'"),seconds=10)
    check('basketball_returns_to_floor',True)
    # Exclusive workstation ownership and expected denials.
    N.acquire('office_computer')
    point=pc('return R.Config.interactables.computer')
    pc('R.World.player.sceneId="warehouse";R.World.player.x=%s;R.World.player.y=%s;return true'%(point['x'],point['y']))
    check('host_cannot_steal_guest_console',pc("local okay=R.acquireLocalWorkshop('office_computer');return not okay"))
    N.release()
    check('console_available_after_release',pc("local okay=R.acquireLocalWorkshop('office_computer');R.releaseLocalWorkshop('closed');return okay"))
    # Independent town travel: the phone leaves while the PC stays at work.
    target=pc("return require('src.home_travel').target({sceneId='warehouse'},R.state)")
    scene('warehouse',target['x'],target['y'])
    interact('guest_explores_independently','homeTravel','explore')
    wait(lambda:phone("return R.World.player.sceneId=='commute'"),seconds=40)
    check('host_remains_in_shop',pc("return R.World.player.sceneId=='warehouse'"))
    token=phone('return R.state.home.commute.token')
    snap('guest-town')
    # Stage the traveler at the store door; enter/cart/checkout use host commands.
    pc("local C=require('src.commute.runtime');local p=R.multiplayer.players[2];local t=R.state.home.commute;local a=t.participants[require('src.home_residents').key(p)];local s=C.world(R).sites.byId.grocery;a.rider.ped.x,a.rider.ped.z=s.door.x,s.door.z;a.rider.bike.x,a.rider.bike.z=s.parking.x,s.parking.z;R.multiplayer:markShopDirty(true);return true")
    time.sleep(1)
    interact('enter_grocery','commute','grocery:'+str(token))
    interact('take_grocery_cart','commute','cartpush:%d:1'%token)
    snap('guest-grocery')
    toolbar=phone("local s,b=R.optionsAccessLayout();return require('src.screens.options_screen').accessRect(s,b)")
    tap(toolbar['x']+toolbar['width']/2,toolbar['y']+toolbar['height']/2)
    check('grocery_options_touch_accessible',phone("return R.state.screen=='options'"))
    tap(868,41)
    check('grocery_options_returns_to_store',phone("return R.state.screen=='world' and R.World.player.sceneId=='grocery'"))
    pc("local p=R.multiplayer.players[2];local a=R.state.home.commute.participants[require('src.home_residents').key(p)];for _,h in ipairs(require('src.commute.grocery_interior').hotspots) do if h.id=='checkout' then a.interiorPose.x,a.interiorPose.y=h.x,h.y end end;R.multiplayer:markShopDirty(true);return true")
    revision=pc('return R.state.home.revision')
    payload=pc("return require('src.commute.town_store').encodeCart({bread=1,vegetables=1})")
    interact('buy_grocery_cart','commute','storecart:%d:%d:%s'%(token,revision,payload))
    check('groceries_in_guest_bike',pc("local r=require('src.home_residents').get(R.state,R.multiplayer.players[2]);return r.bikeInventory.items.bread==1 and r.bikeInventory.items.vegetables==1"))
    interact('exit_grocery','commute','exitgrocery:'+str(token))
    # Stage at apartment parking/entrance, then use the ordinary arrival gate.
    pc("local C=require('src.commute.runtime');local p=R.multiplayer.players[2];local a=R.state.home.commute.participants[require('src.home_residents').key(p)];local s=C.world(R).sites.byId[R.state.home.apartmentId];local parking=require('src.commute.trip').parking(C.world(R),R.state.home.apartmentId,2);a.rider.ped.x,a.rider.ped.z=s.door.x,s.door.z;a.rider.bike.x,a.rider.bike.z=parking.x,parking.z;R.multiplayer:markShopDirty(true);return true")
    time.sleep(.6)
    interact('arrive_apartment','commute','finish:'+str(token))
    wait(lambda:phone("return R.World.player.sceneId=='home'"))
    point=pc("return require('src.home_bike_cargo').target(R.multiplayer.players[2],R.state)");scene('home',point['x'],point['y'])
    revision=pc("return require('src.home_residents').get(R.state,R.multiplayer.players[2]).bikeInventory.revision")
    interact('unload_bike_cargo','homeActivity','bike:all:'+str(revision))
    check('bike_cargo_consumed_once',phone("return next(require('src.home_residents').get(R.state,R.World.player).bikeInventory.items)==nil"))
    layout=pc("local L=require('src.home_layouts');local x,y=L.toWorld(unpack(L.get(R.state).fixtures.sink.approach));return {x=x,y=y}")
    scene('home',layout['x'],layout['y'])
    interact('drink_at_sink','homeActivity','drink:sink')
    wait(lambda:pc("return require('src.home_residents').get(R.state,R.multiplayer.players[2]).activity==nil"),seconds=25)
    check('home_activity_completes',True)
    interact('start_washing','homeActivity','wash:sink')
    interact('cancel_washing','homeActivity','cancel')
    check('home_cancel_releases_fixture',pc("return require('src.home_residents').get(R.state,R.multiplayer.players[2]).activity==nil"))
    check('shared_state_still_valid',pc('local s,e=R.SaveSchema.snapshot(R.state);assert(s,e);assert(R.saveCurrent(true));return true'))
    snap('guest-home')
if __name__=='__main__':main()
