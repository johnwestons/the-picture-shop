"""Package the two corrected north swing roles; stage for engine review by default."""
import argparse
import hashlib
import json
import re
from pathlib import Path
from PIL import Image
import build_luna_player_north_k03_k04_review_v1 as staging
from build_player_north_correction_v1 import lua

ROOT=Path(__file__).resolve().parents[1]
STAGE=ROOT/"output/animation-overhaul/player-north-passing-preview"
RUNTIME="assets/generated/player-walk-v4/walk_north.png"
EXPECTED_PROPOSAL="9ca216c418df69d50687d60c61906ea6243fd828e7d61c87b8aead9ab368db71"


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply",action="store_true")
    args=parser.parse_args()
    staging.main()  # Rechecks immutable masters, exact transforms and v3 base.
    assert hashlib.sha256(staging.PROPOSAL.read_bytes()).hexdigest()==EXPECTED_PROPOSAL
    strip=Image.open(staging.PROPOSAL).convert("RGBA")
    base=Image.open(staging.V3).convert("RGBA")
    for i in (0,1,4,5,6,7):
        assert strip.crop((i*512,0,(i+1)*512,512)).tobytes()==base.crop((i*512,0,(i+1)*512,512)).tobytes()
    destination=ROOT if args.apply else STAGE
    target=destination/RUNTIME;target.parent.mkdir(parents=True,exist_ok=True)
    target.write_bytes(staging.PROPOSAL.read_bytes())
    line=next(s for s in (ROOT/"src/character_anchors.lua").read_text().splitlines() if s.strip().startswith("walk_north ="))
    anchors=[{"x":float(x),"y":float(y)} for x,y in re.findall(r"x\s*=\s*([\d.]+),\s*y\s*=\s*([\d.]+)",line)]
    assert len(anchors)==8
    for i in (2,3,4):anchors[i]={"x":256,"y":465}
    metrics=[list(strip.crop((i*512,0,(i+1)*512,512)).getchannel("A").point(lambda a:255 if a>16 else 0).getbbox()) for i in range(8)]
    art={"paths":{"rabbit-worker":{"walk_north":target.relative_to(ROOT).as_posix()}},
        "anchors":{"rabbit-worker":{"walk_north":anchors}},"metrics":{"rabbit-worker":{"walk_north":metrics}}}
    module=destination/"src/player_walk_art.lua";module.parent.mkdir(parents=True,exist_ok=True)
    module.write_text("-- Generated by tools/build_player_north_passing_v1.py.\nreturn "+lua(art)+"\n",encoding="utf-8")
    report={"status":"installed" if args.apply else "staged for root production review",
        "runtime":target.relative_to(ROOT).as_posix(),"runtime_sha256":EXPECTED_PROPOSAL,
        "provenance":staging.MANIFEST.relative_to(ROOT).as_posix(),
        "provenance_sha256":hashlib.sha256(staging.MANIFEST.read_bytes()).hexdigest(),
        "scope":"Only3/4 replace v3; six other cells including corrected5 and cleaned7 are pixel-exact.",
        "transform":"Each new source uses the same frozen .40773276015281634 scale and rigid translation; no per-part fitting.",
        "remaining":"New3/4 and accepted5 have larger head masks than some original keys. Other canonical proportions and16-frame transitions remain unapproved."}
    (target.parent/"manifest.json").write_text(json.dumps(report,indent=2)+"\n",encoding="utf-8")
    spec=json.loads((ROOT/"character-motion/rabbit-worker.json").read_text(encoding="utf-8"))
    spec["animations"]["walk_north"]["path"]=target.relative_to(ROOT).as_posix()
    STAGE.mkdir(parents=True,exist_ok=True)
    (STAGE/"staging-spec.json").write_text(json.dumps(spec,indent=2)+"\n",encoding="utf-8")
    print(json.dumps(report,indent=2))


if __name__=="__main__":main()
