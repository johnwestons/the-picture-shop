"""Package the staged eight-pose cat walk for engine review; --apply installs."""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image,ImageDraw

ROOT=Path(__file__).resolve().parents[1]
SOURCE="assets/source/animation-overhaul-luna-v1/cat-worker/canonical-replacements/walk_south-corrected-canonical-8phase-proposal-key03v1.png"
EXPECTED="360ec1aa4523cc71049a308c6253622c673b011fc0ac0744246e9ab7dacf05ab"
PROVENANCE="assets/source/animation-overhaul-luna-v1/cat-worker/canonical-replacements/walk_south-canonical-key03-correction-candidate-v1.json"
PROVENANCE_HASH="c24eee4e7168ad44426d57205878ff8eb2160f8676e5c5109406e52f3584bf27"
RUNTIME="assets/generated/worker-walk-v3/cat-worker/walk_south.png"
STAGE=ROOT/"output/animation-overhaul/cat-south-install-preview"


def lua(value):
    if isinstance(value,dict):
        return "{"+",".join("["+json.dumps(k)+"]="+lua(v) for k,v in value.items())+"}"
    if isinstance(value,list):return "{"+",".join(map(lua,value))+"}"
    return json.dumps(value)


def preview(strip,metrics):
    # Enlarge the actual shared world scale by 2 for inspection. Never fit
    # individual poses to their separate alpha bounds.
    factor=2*.30*256/max(b[3]-b[1] for b in metrics)
    side=round(256*factor)
    frames=[]
    for i in range(8):
        canvas=Image.new("RGBA",(256,230),(40,44,48,255))
        cell=strip.crop((i*256,0,(i+1)*256,256)).resize((side,side),Image.Resampling.NEAREST)
        draw=ImageDraw.Draw(canvas)
        draw.text((9,8),f"Cat south | pose {i+1}/8",fill=(240,240,230))
        draw.text((9,215),"2x view | 8 authored poses",fill=(190,198,200))
        canvas.alpha_composite(cell,(round(128-128*factor),round(201-228.5*factor)))
        frames.append(canvas.convert("RGB"))
    palette_source=Image.new("RGB",(256,230*8))
    for i,frame in enumerate(frames):palette_source.paste(frame,(0,i*230))
    palette=palette_source.quantize(colors=256,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
    frames=[f.quantize(palette=palette,dither=Image.Dither.NONE) for f in frames]
    for speed,name in ((1,"nominal"),(2,"half-speed")):
        elapsed=0;delays=[]
        for i in range(8):
            total=round((i+1)*speed*1000*13/72/10)*10
            delays.append(total-elapsed);elapsed=total
        path=STAGE/f"cat-south-{name}.gif"
        frames[0].save(path,save_all=True,append_images=frames[1:],duration=delays,loop=0,disposal=2,optimize=False)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply",action="store_true")
    args=parser.parse_args()
    for name,digest in ((SOURCE,EXPECTED),(PROVENANCE,PROVENANCE_HASH)):
        assert hashlib.sha256((ROOT/name).read_bytes()).hexdigest()==digest, name
    master=Image.open(ROOT/SOURCE).convert("RGBA")
    assert master.size==(4096,512)
    # One scale over the complete master, retaining the authored phase heights.
    strip=master.resize((2048,256),Image.Resampling.LANCZOS)
    destination=ROOT if args.apply else STAGE
    target=destination/RUNTIME;target.parent.mkdir(parents=True,exist_ok=True)
    strip.save(target)
    metrics=[list(strip.crop((i*256,0,(i+1)*256,256)).getchannel("A").point(lambda a:255 if a>16 else 0).getbbox()) for i in range(8)]
    assert all(2<=b[0]<b[2]<=254 and 2<=b[1]<b[3]<=254 for b in metrics)
    hashes=[hashlib.sha256(strip.crop((i*256,0,(i+1)*256,256)).tobytes()).hexdigest() for i in range(8)]
    assert len(set(hashes))==8
    path=target.relative_to(ROOT).as_posix()
    art={"paths":{"cat-worker":{"walk_south":path}},
         "anchors":{"cat-worker":{"walk_south":[{"x":128,"y":228.5} for _ in range(8)]}},
         "metrics":{"cat-worker":{"walk_south":metrics}}}
    module=destination/"src/worker_walk_art.lua";module.parent.mkdir(parents=True,exist_ok=True)
    module.write_text("-- Generated by tools/build_cat_south_walk_v1.py.\nreturn "+lua(art)+"\n",encoding="utf-8")
    spec=json.loads((ROOT/"character-motion/cat-worker.json").read_text(encoding="utf-8"))
    spec["animations"]["walk_south"]["path"]=path
    STAGE.mkdir(parents=True,exist_ok=True)
    (STAGE/"staging-spec.json").write_text(json.dumps(spec,indent=2)+"\n",encoding="utf-8")
    preview(strip,metrics)
    report={"status":"installed" if args.apply else "staged derivative of reviewed selection; not installed by this run",
        "source":SOURCE,"source_sha256":EXPECTED,"provenance":PROVENANCE,"provenance_sha256":PROVENANCE_HASH,
        "runtime":path,"runtime_sha256":hashlib.sha256(target.read_bytes()).hexdigest(),
        "transform":"Entire 4096x512 source resized once by .5 with Lanczos. No per-cell scaling or deformation.",
        "anchors":[128,228.5],"metrics":metrics,"cell_rgba_hashes":hashes,
        "review":"Root checked complete eight-key contact sheet and all phases through production host/guest desktop/phone renderers. Opposite contact owners and K3/K7 passing roles read consistently at game scale. K3 boot is legitimately partly occluded by satchel/body; it remains distinct from K2 and is not a duplicated drawing.",
        "remaining":"Other directions and sixteen-frame transitions are not accepted. This is a contained south-cycle improvement, not complete character acceptance."}
    (target.parent/"manifest.json").write_text(json.dumps(report,indent=2)+"\n",encoding="utf-8")
    print(json.dumps(report,indent=2))


if __name__=="__main__":main()
