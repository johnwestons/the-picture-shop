"""Promote the six root-reviewed, foot-registered Luna action strips.

Rebuild staging first with build_luna_worker_actions_v1.py. This gate checks
immutable source and reviewed output hashes before writing runtime artifacts.
Without --apply it writes only an installation preview under output/.
"""
import argparse
import hashlib
import json
import shutil
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PINS = ROOT / "assets/source/animation-overhaul-luna-worker-actions-v1/runtime-selection-v2.json"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def lua(value):
    if isinstance(value, dict):
        return "{" + ",".join("[" + json.dumps(k) + "]=" + lua(v) for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "{" + ",".join(map(lua, value)) + "}"
    if isinstance(value, str):
        return json.dumps(value)
    return str(value)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    selection = json.loads(PINS.read_text(encoding="utf-8"))
    destination = ROOT if args.apply else ROOT / "output/animation-overhaul/worker-actions-v2-install-preview"
    art = {"paths": {}, "anchors": {}, "metrics": {}, "frameSize": 256}
    installed = []
    # Validate the entire batch before writing any runtime file.
    for entry in selection["actions"]:
        for key in ("source", "strip"):
            path = ROOT / entry[key]
            assert digest(path) == entry[key + "_sha256"], f"Review pin mismatch: {path}"
        with Image.open(ROOT / entry["strip"]) as image:
            assert image.size == (2048, 256) and image.mode == "RGBA"
    for entry in selection["actions"]:
        character, action = entry["character"], entry["action"]
        relative = f"assets/generated/worker-actions-v2/{character}/{action}.png"
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / entry["strip"], target)
        for section in ("paths", "anchors", "metrics"):
            art[section].setdefault(character, {})
        art["paths"][character][action] = relative
        art["anchors"][character][action] = [{"x": 128, "y": 229} for _ in range(8)]
        image = Image.open(target)
        bounds = []
        for i in range(8):
            alpha = image.crop((i * 256, 0, (i + 1) * 256, 256)).getchannel("A")
            box = alpha.point(lambda a: 255 if a > 16 else 0).getbbox()
            assert box and box[0] > 0 and box[1] > 0 and box[2] < 256 and box[3] < 256, relative
            bounds.append(list(box))
        art["metrics"][character][action] = bounds
        installed.append({**entry, "runtime_path": relative, "runtime_sha256": digest(target)})
    module = destination / "src/worker_work_art.lua"
    module.parent.mkdir(parents=True, exist_ok=True)
    module.write_text("-- Generated by tools/build_worker_actions_v2.py; fixed sole-midpoint anchors.\nreturn " + lua(art) + "\n", encoding="utf-8")
    manifest = destination / "assets/generated/worker-actions-v2/manifest.json"
    manifest.write_text(json.dumps({"version": 2, "selection": str(PINS.relative_to(ROOT)).replace("\\", "/"), "actions": installed}, indent=2) + "\n", encoding="utf-8")
    print(f"{'Installed' if args.apply else 'Staged'} {len(installed)} reviewed action strips: {destination}")


if __name__ == "__main__":
    main()
