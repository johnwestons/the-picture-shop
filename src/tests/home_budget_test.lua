local State=require("src.state")
local Home=require("src.home")
local Calendar=require("src.business_calendar")
local Finance=require("src.household_finances")
local Budget=require("src.home_budget")
local Test={}
local function time(s,hours)
    s.calendar=Calendar.dateFromHours(hours);s.calendar.elapsed=hours%24/24*Calendar.secondsPerDay(s)
end
local function capture(context,state,name,readOnly)
    local folder=os.getenv("PICTURE_SHOP_HOME_PREVIEW_DIR");if not folder then return end
    local screen=require("src.screens.computer_screen").new(readOnly and {remoteCommand=function() error("budget view wrote state") end} or nil)
    screen.tab="home"
    local canvas=love.graphics.newCanvas(960,678);love.graphics.push("all");love.graphics.setCanvas(canvas);love.graphics.clear()
    screen.draw(state,nil,nil,context.assets);love.graphics.pop()
    local data=canvas:newImageData();local bytes=data:encode("png")
    local file=assert(io.open(folder.."/"..name..".png","wb"));file:write(bytes:getString());file:close()
    bytes:release();data:release();canvas:release()
end
function Test.run(context,check)
    local s=State.new();local revision=s.home.revision;local b=Budget.summary(s)
    check("home_budget_initial_five_fridays",b.paydays==5 and b.rentShortfallCents==15000 and b.perPaydayCents==3000 and b.lastPayCents==nil)
    local lines=Budget.lines(s)
    check("home_budget_preview_does_not_mutate",s.home.revision==revision and #lines==3 and not s.home.finance.stockSeeded)
    capture(context,s,"home-budget-first-weekend")
    s.money=10000;Finance.record(s,"revenue",4000);assert(Finance.settle(s,44));b=Budget.summary(s)
    check("home_budget_settled_friday_not_counted_twice",b.paydays==4 and b.lastPayCents==1000 and b.perPaydayCents==3500)
    local _,warning=Budget.lines(s);check("home_budget_low_previous_pay_warns",warning)
    time(s,28*24);b=Budget.summary(s)
    check("home_budget_last_friday_target",b.paydays==1 and b.perPaydayCents==14000)
    time(s,29*24+20);assert(Finance.settle(s,29*24+20));b=Budget.summary(s)
    check("home_budget_rent_before_next_payday",b.paydays==0 and b.perPaydayCents==14000)
    capture(context,s,"home-budget-before-rent")
    time(s,31*24);Home.advance(s);b=Budget.summary(s)
    check("home_budget_arrears_count_with_next_rent",b.dueCents==45000 and b.dueShortfallCents==14000 and b.rentShortfallCents==59000)
    capture(context,s,"home-budget-arrears",true)
    s.home.balanceCents=90000;lines=Budget.lines(s)
    check("home_budget_existing_funds_cover_both_invoices",Budget.summary(s).perPaydayCents==0 and lines[1]=="Rent covered through next due date.")
    local late=State.new();late.home.weekend.phase="closing";time(late,28*24)
    check("home_budget_delayed_shutdown_counts_once",Budget.summary(late).paydays==2)
    late.home.weekend.phase="home";late.home.weekend.closedAtHours=44;Finance.settle(late,44)
    check("home_budget_staying_home_does_not_reuse_old_payday",Budget.summary(late).paydays==1)
    local loss=State.new();time(loss,44);assert(Finance.settle(loss,44))
    check("home_budget_zero_pay_identifies_costs_and_losses",Budget.summary(loss).lastPayReason=="no_earnings" and select(2,Budget.lines(loss)))
    capture(context,loss,"home-budget-no-earnings")
    local reserve=State.new();reserve.money=1680;Finance.record(reserve,"revenue",150000)
    reserve.home.finance.reserveCents=1000000;time(reserve,44);assert(Finance.settle(reserve,44))
    check("home_budget_positive_profit_zero_cash_identifies_reserve",Budget.summary(reserve).lastPayCents==0 and Budget.summary(reserve).lastPayReason=="reserves")
    capture(context,reserve,"home-budget-reserve-limited",true)
    local zero=State.new();zero.money=10000;assert(Home.setPayPercent(zero.home,0,zero.home.revision))
    Finance.record(zero,"revenue",150000);time(zero,44);assert(Finance.settle(zero,44))
    assert(Home.setPayPercent(zero.home,50,zero.home.revision))
    check("home_budget_explains_settled_rate_after_slider_changes",Budget.summary(zero).lastPayReason=="zero_rate" and Budget.summary(zero).lastPayCents==0)
    capture(context,zero,"home-budget-zero-rate")
end
return Test
